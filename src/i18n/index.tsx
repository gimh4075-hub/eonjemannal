export type Translations = typeof t.ko

// ── Context ───────────────────────────────────────────
const LangContext = createContext<{
  lang: Lang
  tr: Translations
  locale: Locale
  setLang: (l: Lang) => void
}>({ lang: 'ko', tr: t.ko, locale: ko, setLang: () => {} })

function getSavedLang(): Lang {
  try {
    const v = localStorage.getItem('eonjemannal_lang')
    if (v && v in t) return v as Lang
  } catch {}
  // 브라우저 언어 자동 감지
  const nav = navigator.language.toLowerCase()
  if (nav.startsWith('ja')) return 'ja'
  if (nav.startsWith('zh')) return 'zh'
  if (nav.startsWith('ko')) return 'ko'
  if (nav.startsWith('en')) return 'en'
  return 'ko'
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getSavedLang)

  function setLang(l: Lang) {
    setLangState(l)
    try { localStorage.setItem('eonjemannal_lang', l) } catch {}
  }

  return (
    <LangContext.Provider value={{ lang, tr: t[lang], locale: dateFnsLocales[lang], setLang }}>
      {children}
    </LangContext.Provider>
  )
}

export function useLang() {
  return useContext(LangContext)
}
